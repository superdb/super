//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"github.com/superdb/super/vector"
)

var opToAlpha = map[string]string{
	"==": "EQ",
	"!=": "NE",
	"<":  "LT",
	"<=": "LE",
	">":  "GT",
	">=": "GE",
}

func main() {
	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by gencomparefuncs.go. DO NOT EDIT.")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "package expr")
	fmt.Fprintln(&buf, `import "github.com/superdb/super/vector"`)

	var ents strings.Builder
	for _, op := range []string{"==", "!=", "<", "<=", ">", ">="} {
		for _, typ := range []string{"Int", "Uint", "Float", "String", "Bytes"} {
			for lform := vector.Form(0); lform < 4; lform++ {
				for rform := vector.Form(0); rform < 4; rform++ {
					name := "compare" + opToAlpha[op] + typ + lform.String() + rform.String()
					fmt.Fprintln(&buf, genFunc(name, op, typ, lform, rform))
					funcCode := vector.FuncCode(vector.CompareOpFromString(op), vector.KindFromString(typ), lform, rform)
					fmt.Fprintf(&ents, "%d: %s,\n", funcCode, name)
				}
			}
		}
	}

	fmt.Fprintln(&buf, "var compareFuncs = map[int]func(vector.Any, vector.Any) vector.Any{")
	fmt.Fprintln(&buf, ents.String())
	fmt.Fprintln(&buf, "}")

	out, formatErr := format.Source(buf.Bytes())
	if formatErr != nil {
		// Write unformatted source so we can find the error.
		out = buf.Bytes()
	}
	const fileName = "comparefuncs.go"
	if err := os.WriteFile(fileName, out, 0644); err != nil {
		log.Fatal(err)
	}
	if formatErr != nil {
		log.Fatal(fileName, ":", formatErr)
	}
}

func genFunc(name, op, typ string, lhs, rhs vector.Form) string {
	s := fmt.Sprintf("func %s(lhs, rhs vector.Any) vector.Any {\n", name)
	if (lhs == vector.FormDict && rhs == vector.FormConst) || (lhs == vector.FormConst && rhs == vector.FormDict) {
		s += genDictConstBody(op, typ, rhs)
	} else {
		s += genFuncBody(op, typ, lhs, rhs)
	}
	s += "}\n"
	return s
}

func genFuncBody(op, typ string, lhs, rhs vector.Form) string {
	s := genVarInit("l", typ, lhs)
	s += genVarInit("r", typ, rhs)
	lexpr := genExpr("l", lhs)
	rexpr := genExpr("r", rhs)
	if typ == "Bytes" {
		lexpr = "string(" + lexpr + ")"
		rexpr = "string(" + rexpr + ")"
	}
	cond := fmt.Sprintf("%s %s %s", lexpr, op, rexpr)
	if typ == "Float" {
		cond = floatCond(op)
	}
	if lhs == vector.FormConst && rhs == vector.FormConst {
		if typ == "Float" {
			s += fmt.Sprintf("a, b := %s, %s\n", lexpr, rexpr)
		}
		s += fmt.Sprintf("return vector.NewConstBool(%s, lhs.Len())\n", cond)
		return s
	}
	s += "n := lhs.Len()\n"
	s += "out := vector.NewFalse(n)\n"
	s += "for k := range n {\n"
	if typ == "Float" {
		s += fmt.Sprintf("a, b := %s, %s\n", lexpr, rexpr)
	}
	s += fmt.Sprintf("if %s { out.Set(k) }}\n", cond)
	s += "return out\n"
	return s
}

func genDictConstBody(op, typ string, rhs vector.Form) string {
	d, c := "lhs", "rhs"
	if rhs == vector.FormDict {
		d, c = c, d
	}
	s := fmt.Sprintf("d := %s.(*vector.Dict)\n", d)
	s += fmt.Sprintf("dv := d.Any.(*vector.%s)\n", typ)
	s += fmt.Sprintf("c := %s.(*vector.Const).Any.(*vector.%s).Value(0)\n", c, typ)
	s += "result := make([]bool, dv.Len())\n"
	lexpr := "dv.Value(k)"
	rexpr := "c"
	if rhs == vector.FormDict {
		lexpr, rexpr = rexpr, lexpr
	}
	if typ == "Bytes" {
		lexpr = fmt.Sprintf("string(%s)", lexpr)
		rexpr = fmt.Sprintf("string(%s)", rexpr)
	}
	cond := fmt.Sprintf("%s %s %s", lexpr, op, rexpr)
	if typ == "Float" {
		cond = floatCond(op)
	}
	s += "for k := range dv.Len() {\n"
	if typ == "Float" {
		s += fmt.Sprintf("a, b := %s, %s\n", lexpr, rexpr)
	}
	s += fmt.Sprintf("result[k] = %s}\n", cond)
	s += "n := lhs.Len()\n"
	s += "out := vector.NewFalse(n)\n"
	s += "for k := range n {\n"
	s += "if result[d.Index[k]] { out.Set(k) }}\n"
	s += "return out\n"
	return s
}

// floatCond returns the condition for op on floats a and b, which orders NaN
// after all other values and equal to NaN (as Postgres does).
func floatCond(op string) string {
	switch op {
	case "==":
		return "a == b || a != a && b != b"
	case "!=":
		return "!(a == b || a != a && b != b)"
	case "<":
		return "a < b || a == a && b != b"
	case "<=":
		return "a <= b || b != b"
	case ">":
		return "a > b || a != a && b == b"
	case ">=":
		return "a >= b || a != a"
	}
	panic(op)
}

func genVarInit(which, typ string, form vector.Form) string {
	switch form {
	case vector.FormFlat:
		return fmt.Sprintf("%s := %shs.(*vector.%s)\n", which, which, typ)
	case vector.FormDict, vector.FormView:
		s := fmt.Sprintf("%sd := %shs.(*vector.%s)\n", which, which, form)
		s += fmt.Sprintf("%s := %sd.Any.(*vector.%s)\n", which, which, typ)
		s += fmt.Sprintf("%sx := %sd.Index\n", which, which)
		return s
	case vector.FormConst:
		return fmt.Sprintf("%sconst := %shs.(*vector.Const).Any.(*vector.%s).Value(0)\n", which, which, typ)
	}
	panic(form)
}

func genExpr(which string, form vector.Form) string {
	switch form {
	case vector.FormFlat:
		return which + ".Value(k)"
	case vector.FormDict, vector.FormView:
		return fmt.Sprintf("%s.Value(uint32(%sx[k]))", which, which)
	case vector.FormConst:
		return which + "const"
	}
	panic(form)
}
